// Original vertical town art; each district joins the same road.
export function districtArt(zone = 1) {
  let p = "";
  const r = (x, y, w, h, c) =>
    (p += `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${c}"/>`);
  const poly = (points, c) =>
    (p += `<polygon points="${points}" fill="${c}"/>`);
  r(0, 0, 390, 650, ["#57768c", "#789eaa", "#697d9b"][zone]);
  r(0, 95, 390, 100, "#bed4ba");
  poly(
    "0,205 35,120 85,166 144,88 198,157 257,103 319,163 375,107 390,205",
    "#668c83",
  );
  poly(
    "0,218 66,174 130,206 205,161 284,202 350,164 390,221 390,290 0,290",
    "#477866",
  );
  r(0, 250, 390, 400, "#6f9363");
  r(0, 370, 390, 280, "#7a9b64");
  poly("144,305 214,305 267,650 103,650", "#baaa80");
  r(0, 490, 390, 48, "#baaa80");
  for (let y = 328; y < 650; y += 16)
    for (let x = 140; x < 232; x += 20)
      r(x + (y % 32 ? 0 : 8), y, 13, 4, "#a99b74");
  const tree = (x, y) => {
    r(x + 14, y + 40, 10, 40, "#675740");
    r(x + 18, y + 47, 3, 30, "#9b8056");
    r(x, y + 14, 38, 39, "#345b4e");
    r(x + 5, y + 4, 29, 42, "#4c7c5b");
    r(x + 10, y, 19, 27, "#77a16b");
  };
  for (const [x, y] of [
    [2, 212],
    [348, 214],
    [8, 379],
    [339, 368],
    [11, 557],
    [342, 576],
  ])
    tree(x, y);
  const house = (x, y, w, h, color, sign) => {
    r(x - 5, y + h, w + 10, 8, "#45644c");
    r(x, y, w, h, "#d8c693");
    r(x + 5, y + 5, w - 10, h - 5, "#baa777");
    r(x, y, 5, h, "#745d47");
    r(x + w - 5, y, 5, h, "#745d47");
    poly(
      `${x - 10},${y + 3} ${x + w / 2},${y - 43} ${x + w + 10},${y + 3}`,
      color,
    );
    for (let j = 0; j < 5; j++)
      r(x + 8 + j * 7, y - 30 + j * 7, w - 16 - j * 14, 3, "#ffffff22");
    r(x + w / 2 - 12, y + h - 35, 24, 35, "#625845");
    r(x + w / 2 - 8, y + h - 31, 16, 30, "#8a7250");
    r(x + 12, y + 17, 16, 22, "#5a777b");
    r(x + 14, y + 19, 12, 17, "#f0d88f");
    r(x + w - 28, y + 17, 16, 22, "#5a777b");
    r(x + w - 26, y + 19, 12, 17, "#f0d88f");
    r(x + w / 2 - 22, y + 9, 44, 12, sign);
  };
  if (zone === 0) {
    house(25, 287, 118, 108, "#6b6292", "#e0c582");
    house(242, 370, 112, 102, "#5d8291", "#a8d1c5");
    house(230, 235, 98, 84, "#9c7969", "#edc083");
  }
  if (zone === 1) {
    house(25, 281, 100, 93, "#977165", "#d9c997");
    house(255, 286, 108, 94, "#658194", "#c5dfba");
    r(144, 187, 95, 117, "#bec9a2");
    r(150, 179, 83, 117, "#d7d7b2");
    r(138, 180, 107, 13, "#657c73");
    for (const x of [148, 177, 218]) r(x, 164, 15, 25, "#ddd5ae");
    r(181, 252, 24, 52, "#486a69");
    r(169, 264, 48, 40, "#68958b");
    r(186, 258, 15, 35, "#9de0c4");
    r(193, 153, 3, 40, "#7c6a49");
    r(196, 153, 27, 14, "#b4828b");
    r(157, 422, 78, 19, "#4f807d");
    r(165, 414, 62, 16, "#a7bba6");
    r(175, 417, 43, 7, "#88cad0");
    r(191, 391, 8, 24, "#cad3bc");
    r(185, 388, 21, 5, "#b4c7ae");
  }
  if (zone === 2) {
    house(25, 248, 118, 107, "#95698b", "#dbc17d");
    house(236, 302, 123, 113, "#8a6258", "#e4bf78");
    house(33, 428, 110, 96, "#5e8190", "#b3d4ba");
    r(307, 266, 13, 38, "#6e5b4a");
    r(301, 260, 24, 9, "#7f6a54");
    r(298, 257, 30, 6, "#d79f78");
  }
  for (let i = 0; i < 25; i++) {
    const x = (i * 73 + 7) % 386,
      y = 310 + ((i * 29) % 330);
    r(x, y, 3, 4, "#c0bd78");
    if (i % 3 === 0) {
      r(x, y - 2, 3, 3, "#e3b9aa");
      r(x + 3, y + 1, 3, 2, "#c58a96");
    }
  }
  return `<svg class="district-art pixel-scene" viewBox="0 0 390 650" preserveAspectRatio="xMidYMid slice" shape-rendering="crispEdges" aria-hidden="true">${p}</svg>`;
}
